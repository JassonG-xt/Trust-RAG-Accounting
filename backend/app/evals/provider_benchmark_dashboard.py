"""Phase 8D — read-only reader for Phase 8C provider benchmark artifacts.

The dashboard needs to *display* provider benchmark results without ever running
a benchmark or touching a real provider. This module reads the artifacts the
Phase 8C CLI already writes:

* ``data/provider_benchmark_results.json`` — the single most-recent result.
* ``data/provider_benchmarks/*.json`` — optional archived snapshots.
* ``data/provider_benchmark_report.md`` — the optional Markdown report.

It mirrors :mod:`backend.app.evals.history`: glob, skip malformed JSON, sort
newest-first, apply a limit, and return ``available=false`` when nothing is on
disk. Two extra guarantees matter for a read-only endpoint that surfaces
arbitrary local JSON:

* **No secrets / no evidence content.** Every artifact dict is recursively
  scrubbed of sensitive keys (api keys, tokens, …) and evidence-content keys
  (``content`` / ``snippet`` / ``answer`` / ``claim_text`` / any ``*_evidence`` /
  raw provider payloads) before it leaves this module — defense-in-depth even
  though the Phase 8C artifacts never contain them. The one exception is the
  Markdown report: it is generated by ``provider_benchmark_report.py``
  (names / ids / counts only) and rendered via ``textContent`` in the dashboard,
  so it is trusted-by-construction and passed through verbatim rather than
  scrubbed.
* **Bounded list payload.** ``latest`` carries the full newest artifact
  (including per-case ``results`` for the case table); the ``artifacts`` list
  carries *compact* copies (everything except the heavy ``results`` array) so the
  comparison payload stays small even with many archived snapshots.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

from pydantic import BaseModel, Field

logger = logging.getLogger("trust_rag.evals.provider_benchmark_dashboard")

# Keys dropped from any artifact before it leaves this module. Sensitive names
# guard against a tampered/hand-edited artifact; evidence-content names guard
# against ever surfacing document bodies through the dashboard.
_SENSITIVE_FRAGMENTS = (
    "api_key",
    "apikey",
    "api-key",
    "secret",
    "token",
    "password",
    "authorization",
    "bearer",
)
# Evidence / answer-prose keys. Matched generously (substring fragments + an
# ``_evidence`` suffix via the "evidence" fragment) so a tampered or
# misconfigured artifact that embeds a full RAG response (answer body, claim
# prose, retrieved snippets, raw provider payloads) can never surface document
# prose through the dashboard. Fragments are chosen to avoid over-matching
# benign benchmark keys — no bare ``text`` (it would eat ``context`` /
# ``document_type``-style names); none of the real benchmark fields contain
# ``evidence`` / ``raw_`` / ``answer`` / ``content``.
_EVIDENCE_FRAGMENTS = ("evidence", "snippet", "raw_", "claim_text", "answer_text")
_EVIDENCE_EXACT = {"content", "answer", "quote", "excerpt", "passage", "body"}


class ProviderBenchmarkArtifactSummary(BaseModel):
    """Read-only projection of provider benchmark artifacts for the dashboard."""

    available: bool
    count: int
    latest: dict[str, Any] | None = None
    artifacts: list[dict[str, Any]] = Field(default_factory=list)
    markdown_report: str | None = None


def _is_droppable_key(key: Any) -> bool:
    name = str(key).lower()
    if any(fragment in name for fragment in _SENSITIVE_FRAGMENTS):
        return True
    if any(fragment in name for fragment in _EVIDENCE_FRAGMENTS):
        return True
    return name in _EVIDENCE_EXACT


def _scrub(value: Any) -> Any:
    """Recursively drop sensitive / evidence-content keys from a parsed artifact."""

    if isinstance(value, dict):
        return {k: _scrub(v) for k, v in value.items() if not _is_droppable_key(k)}
    if isinstance(value, list):
        return [_scrub(v) for v in value]
    return value


def _read_json_object(path: Path) -> dict[str, Any] | None:
    """Read a JSON object, returning None for malformed / non-object files."""

    try:
        parsed = json.loads(path.read_text(encoding="utf-8"))
    except Exception as exc:
        logger.warning("skipping malformed provider benchmark artifact %s: %s", path, exc)
        return None
    if not isinstance(parsed, dict):
        logger.warning("skipping non-object provider benchmark artifact %s", path)
        return None
    return parsed


def _read_markdown(path: Path | None) -> str | None:
    if path is None or not path.exists() or not path.is_file():
        return None
    try:
        return path.read_text(encoding="utf-8")
    except Exception as exc:  # pragma: no cover - defensive
        logger.warning("failed to read provider benchmark report %s: %s", path, exc)
        return None


def load_provider_benchmark_artifacts(
    *,
    single_result_path: Path,
    benchmark_dir: Path,
    markdown_report_path: Path | None = None,
    limit: int | None = None,
    provider: str | None = None,
) -> ProviderBenchmarkArtifactSummary:
    """Load provider benchmark artifacts into a read-only dashboard summary.

    Reads the single result file *and* any ``*.json`` under ``benchmark_dir``,
    sorts newest-first by file mtime (filename breaks ties), filters by
    ``provider`` when given, applies ``limit``, and scrubs secrets / evidence.
    """

    # (sort_mtime, filename, scrubbed_dict)
    candidates: list[tuple[float, str, dict[str, Any]]] = []
    seen_paths: set[Path] = set()

    def _consider(path: Path) -> None:
        # Dedup by resolved path so a results file that also lives inside
        # benchmark_dir is never counted twice.
        try:
            resolved = path.resolve()
        except OSError:  # pragma: no cover - defensive
            resolved = path
        if resolved in seen_paths:
            return
        seen_paths.add(resolved)
        parsed = _read_json_object(path)
        if parsed is None:
            return
        candidates.append((path.stat().st_mtime, path.name, _scrub(parsed)))

    if single_result_path.exists() and single_result_path.is_file():
        _consider(single_result_path)

    if benchmark_dir.exists() and benchmark_dir.is_dir():
        for path in benchmark_dir.glob("*.json"):
            _consider(path)

    if provider:
        candidates = [c for c in candidates if str(c[2].get("provider")) == provider]

    # Newest-first; filename breaks ties so the order is deterministic.
    candidates.sort(key=lambda c: (c[0], c[1]), reverse=True)

    # Non-positive limit yields no artifacts (0 and negative behave the same).
    if limit is not None:
        candidates = candidates[: max(limit, 0)]

    markdown_report = _read_markdown(markdown_report_path)

    if not candidates:
        return ProviderBenchmarkArtifactSummary(
            available=False,
            count=0,
            latest=None,
            artifacts=[],
            markdown_report=markdown_report,
        )

    latest = dict(candidates[0][2])
    latest["source"] = candidates[0][1]

    artifacts: list[dict[str, Any]] = []
    for _mtime, name, parsed in candidates:
        compact = {k: v for k, v in parsed.items() if k != "results"}
        compact["source"] = name
        artifacts.append(compact)

    return ProviderBenchmarkArtifactSummary(
        available=True,
        count=len(candidates),
        latest=latest,
        artifacts=artifacts,
        markdown_report=markdown_report,
    )


__all__ = [
    "ProviderBenchmarkArtifactSummary",
    "load_provider_benchmark_artifacts",
]
